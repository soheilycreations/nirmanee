// Generates supabase/seed.sql from supabase/seed/catalog.json.
// Usage: npm run db:seed
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(path.join(root, "supabase/seed/catalog.json"), "utf8"));

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replaceAll("'", "''")}'`;
};
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

const out = [
  "-- GENERATED by scripts/build-seed.mjs from supabase/seed/catalog.json — do not edit by hand.",
  "-- Prices are placeholders until confirmed by the owner. Sinhala text is a draft.",
  "begin;",
  "",
];

for (const c of catalog.categories) {
  out.push(
    `insert into public.categories (slug, name_en, name_si, description_en, description_si, sort_order) values (` +
      [c.slug, c.name_en, c.name_si, c.description_en, c.description_si, c.sort_order].map(q).join(", ") +
      `) on conflict (slug) do update set name_en = excluded.name_en, name_si = excluded.name_si, ` +
      `description_en = excluded.description_en, description_si = excluded.description_si, sort_order = excluded.sort_order;`,
  );
}
out.push("");

for (const p of catalog.products) {
  const specs = (p.specs ?? []).map(([label_en, value_en]) => ({ label_en, value_en }));
  out.push(`-- ${p.slug}`);
  out.push(
    `insert into public.products (category_id, slug, name_en, name_si, short_description_en, short_description_si, description_en, description_si, ` +
      `order_type, pricing_mode, base_price, price_per_sqft, min_sqft, production_days, express_days, express_surcharge_percent, design_fee, ` +
      `allow_customer_artwork, allow_design_service, requires_artwork, images, specs, is_featured, sort_order) ` +
      `select c.id, ${[
        p.slug, p.name_en, p.name_si, p.short_en, p.short_si, p.description_en, p.description_si,
      ].map(q).join(", ")}, ${q(p.order_type)}::public.order_type, ${q(p.pricing_mode)}::public.pricing_mode, ` +
      `${[p.base_price ?? null, p.price_per_sqft ?? null, p.min_sqft ?? null, p.production_days, p.express_days ?? null,
          p.express_surcharge_percent ?? 50, p.design_fee ?? 0, p.allow_customer_artwork ?? true,
          p.allow_design_service ?? true, p.requires_artwork ?? true].map(q).join(", ")}, ` +
      `${j(p.images ?? [])}, ${j(specs)}, ${q(Boolean(p.featured))}, ${q(p.sort_order ?? 0)} ` +
      `from public.categories c where c.slug = ${q(p.category)} on conflict (slug) do nothing;`,
  );
  const pid = `(select id from public.products where slug = ${q(p.slug)})`;
  for (const [min, pct] of p.tiers ?? []) {
    out.push(`insert into public.product_price_tiers (product_id, min_quantity, discount_percent) values (${pid}, ${min}, ${pct}) on conflict do nothing;`);
  }
  (p.options ?? []).forEach((o, i) => {
    out.push(
      `insert into public.product_options (product_id, type, code, label_en, label_si, is_required, config, sort_order) values (` +
        `${pid}, ${q(o.type)}::public.option_type, ${q(o.code)}, ${q(o.label_en)}, ${q(o.label_si)}, ` +
        `${q(o.is_required ?? true)}, ${j(o.config ?? {})}, ${(i + 1) * 10}) on conflict (product_id, code) do nothing;`,
    );
    const oid = `(select id from public.product_options where product_id = ${pid} and code = ${q(o.code)})`;
    (o.values ?? []).forEach((v, k) => {
      out.push(
        `insert into public.product_option_values (option_id, label_en, label_si, value, modifier_type, price_modifier, width_in, height_in, swatch_hex, is_default, sort_order) values (` +
          `${oid}, ${q(v.label_en)}, ${q(v.label_si)}, ${q(v.value)}, ${q(v.modifier_type ?? "flat")}::public.price_modifier_type, ` +
          `${[v.price_modifier ?? 0, v.width_in ?? null, v.height_in ?? null, v.swatch_hex ?? null, Boolean(v.is_default), (k + 1) * 10].map(q).join(", ")}) ` +
          `on conflict (option_id, value) do nothing;`,
      );
    });
  });
  (p.templates ?? []).forEach((t, i) => {
    out.push(
      `insert into public.product_templates (product_id, name_en, name_si, preview_key, sort_order) ` +
        `select ${pid}, ${[t.name_en, t.name_si, t.preview_key].map(q).join(", ")}, ${(i + 1) * 10} ` +
        `where not exists (select 1 from public.product_templates where product_id = ${pid} and name_en = ${q(t.name_en)});`,
    );
  });
  out.push("");
}

out.push("commit;", "");
writeFileSync(path.join(root, "supabase/seed.sql"), out.join("\n"));
console.log(`seed.sql written: ${catalog.categories.length} categories, ${catalog.products.length} products`);
